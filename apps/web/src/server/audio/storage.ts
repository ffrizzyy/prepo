import { createHash } from "node:crypto";
import {
  appendFile,
  mkdir,
  open,
  readFile,
  readdir,
  rm,
  stat,
  writeFile,
  type FileHandle,
} from "node:fs/promises";
import path from "node:path";

/**
 * Where audio bytes live.
 *
 * The specification puts recordings in a private Cloudflare R2 bucket and hands
 * the browser a presigned URL (PREPO.md §6.2). There is no R2 account behind this
 * repository, so the driver here is the local filesystem: the same private-key
 * discipline and the same rule that bytes are never reachable without an
 * authorization check, with no bucket to configure. A bucket driver implements
 * this interface and nothing else changes.
 *
 * Keys are opaque and generated by the server, a client never supplies one.
 */

export type StoredObject = { key: string; sizeBytes: number };

export interface StorageDriver {
  readonly name: string;
  put(key: string, bytes: Uint8Array): Promise<StoredObject>;
  /** Reads the whole object. Only for pieces small enough to buffer. */
  read(key: string): Promise<Uint8Array>;
  /** Byte length, or null when the object does not exist. */
  size(key: string): Promise<number | null>;
  /** Reads an inclusive byte range in one shot. */
  readRange(key: string, start: number, end: number): Promise<Uint8Array | null>;
  /** Opens a handle so a caller can read a range itself and close it. */
  open(key: string): Promise<{ handle: FileHandle; size: number } | null>;
  remove(key: string): Promise<void>;
}

/** Nested one level per workspace, so no single directory grows without bound. */
export function audioKey(input: {
  workspaceId: string;
  assetId: string;
  extension: string;
}): string {
  const extension = input.extension.startsWith(".") ? input.extension : `.${input.extension}`;
  return `${input.workspaceId}/${input.assetId}${extension}`;
}

export function contentHash(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}

/**
 * The local driver. Every path is resolved and then checked to still be inside
 * the root, so a key can never escape the storage directory.
 */
class LocalStorageDriver implements StorageDriver {
  readonly name = "local";
  private readonly root: string;

  constructor(root: string) {
    this.root = path.resolve(root);
  }

  private resolve(key: string): string {
    if (key.length === 0 || key.includes("\0")) throw new Error("Invalid storage key");
    const resolved = path.resolve(this.root, key);
    const prefix = this.root.endsWith(path.sep) ? this.root : `${this.root}${path.sep}`;
    if (!resolved.startsWith(prefix)) throw new Error("Storage key escapes the root");
    return resolved;
  }

  async put(key: string, bytes: Uint8Array): Promise<StoredObject> {
    const target = this.resolve(key);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, bytes);
    return { key, sizeBytes: bytes.byteLength };
  }

  async read(key: string): Promise<Uint8Array> {
    return new Uint8Array(await readFile(this.resolve(key)));
  }

  async size(key: string): Promise<number | null> {
    const info = await stat(this.resolve(key)).catch(() => null);
    return info?.size ?? null;
  }

  async readRange(key: string, start: number, end: number): Promise<Uint8Array | null> {
    const info = await stat(this.resolve(key)).catch(() => null);
    if (!info) return null;
    const length = end - start + 1;
    const buffer = Buffer.alloc(length);
    const handle = await open(this.resolve(key), "r");
    try {
      const { bytesRead } = await handle.read(buffer, 0, length, start);
      return new Uint8Array(buffer.subarray(0, bytesRead));
    } finally {
      await handle.close();
    }
  }

  async open(key: string) {
    const handle = await open(this.resolve(key), "r").catch(() => null);
    if (!handle) return null;
    const info = await handle.stat();
    return { handle, size: info.size };
  }

  async remove(key: string): Promise<void> {
    await rm(this.resolve(key), { force: true });
  }
}

let cached: StorageDriver | null = null;

export function audioStorage(): StorageDriver {
  cached ??= new LocalStorageDriver(
    process.env.AUDIO_STORAGE_DIR ?? path.join(process.cwd(), ".storage", "audio"),
  );
  return cached;
}

/** Test seam: lets the smoke test point the driver at a scratch directory. */
export function setAudioStorage(driver: StorageDriver | null): void {
  cached = driver;
}

/* ------------------------------------------------- chunked upload staging */

/**
 * A browser recording arrives in pieces so that a dropped connection does not
 * lose the whole thing (PREPO.md §6.1). Pieces are staged as a single `.part`
 * file and assembled once the client says it is done; a stale piece is garbage
 * after an hour, which the retention sweep reclaims.
 */
function stagingRoot(): string {
  return process.env.AUDIO_STAGING_DIR ?? path.join(process.cwd(), ".storage", "incoming");
}

function uploadPaths(uploadId: string): { dir: string; part: string; meta: string } {
  if (!/^[0-9a-f-]{36}$/i.test(uploadId)) throw new Error("Invalid upload id");
  const dir = path.join(stagingRoot(), uploadId);
  return { dir, part: path.join(dir, "audio.part"), meta: path.join(dir, "upload.json") };
}

export type UploadMeta = {
  workspaceId: string;
  userId: string;
  title: string;
  heldAt: string;
  source: "recording" | "upload";
  consent: true;
  filename: string;
  /** Bytes the client promises in total; checked when assembling. */
  totalBytes: number;
  nextIndex: number;
  createdAt: string;
};

export async function beginUpload(uploadId: string, meta: UploadMeta): Promise<void> {
  const { meta: metaPath } = uploadPaths(uploadId);
  await mkdir(path.dirname(metaPath), { recursive: true });
  await writeFile(metaPath, JSON.stringify(meta), "utf8");
}

export async function readUploadMeta(uploadId: string): Promise<UploadMeta | null> {
  const { meta } = uploadPaths(uploadId);
  const raw = await readFile(meta, "utf8").catch(() => null);
  if (!raw) return null;
  try {
    return JSON.parse(raw) as UploadMeta;
  } catch {
    return null;
  }
}

/** Appends one piece and returns how many bytes have landed so far. */
export async function appendChunk(
  uploadId: string,
  index: number,
  bytes: Uint8Array,
): Promise<number> {
  const { part } = uploadPaths(uploadId);
  const current = await stat(part).catch(() => null);
  if (current && index === 0) await rm(part, { force: true });
  if (!current && index > 0) throw new Error("Upload piece arrived out of order");
  await mkdir(path.dirname(part), { recursive: true });
  await appendFile(part, bytes);
  return (await stat(part)).size;
}

export async function readStagedUpload(uploadId: string): Promise<Uint8Array | null> {
  const { part } = uploadPaths(uploadId);
  const bytes = await readFile(part).catch(() => null);
  return bytes ? new Uint8Array(bytes) : null;
}

export async function clearUpload(uploadId: string): Promise<void> {
  const { dir } = uploadPaths(uploadId);
  await rm(dir, { recursive: true, force: true });
}

/** Reclaims staged uploads the client never finished. */
export async function sweepStaleUploads(maxAgeMs: number): Promise<number> {
  const root = stagingRoot();
  const entries = await readdir(root, { withFileTypes: true }).catch(() => []);
  let removed = 0;

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const target = path.join(root, entry.name);
    const info = await stat(target).catch(() => null);
    if (!info || Date.now() - info.mtimeMs < maxAgeMs) continue;
    await rm(target, { recursive: true, force: true });
    removed += 1;
  }

  return removed;
}
